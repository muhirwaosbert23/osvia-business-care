import { spawn } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { projectRoot } from "../server/env.js";
import { bootstrap } from "../test/helpers.js";

const DURATION_MS = Number(process.env.LOADTEST_SECONDS || 20) * 1000;
const CONCURRENCY = Number(process.env.LOADTEST_CONCURRENCY || 25);
const TICKETS = Number(process.env.LOADTEST_TICKETS || 300);
const DEVICES = Number(process.env.LOADTEST_DEVICES || 150);
const PORT = Number(process.env.LOADTEST_PORT || 3099);

const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), "osvia-load-"));
const child = spawn(process.execPath, ["--experimental-sqlite", "--no-warnings=ExperimentalWarning", path.join(projectRoot, "server", "index.js")], {
  env: { ...process.env, HOST: "127.0.0.1", PORT: String(PORT), DATA_DIR: dataDir, DISABLE_JOBS: "true", NODE_ENV: "development", SMTP_HOST: "", MESHCENTRAL_URL: "" },
  stdio: ["ignore", "inherit", "inherit"],
  windowsHide: true,
});
const base = `http://127.0.0.1:${PORT}`;
for (let i = 0; ; i++) {
  try {
    if ((await fetch(`${base}/api/health`)).ok) break;
  } catch {
    if (i > 50 || child.exitCode !== null) throw new Error(`The portal did not start on port ${PORT}.`);
    await new Promise((resolve) => setTimeout(resolve, 200));
  }
}

console.log(`Seeding a throwaway database in ${dataDir}`);
const { admin, tech, custA, userA, orgA, orgB } = await bootstrap(base);
for (let i = 0; i < DEVICES; i++) {
  const res = await admin.post("/api/devices", { organizationId: i % 2 ? orgA : orgB, name: `Load PC ${i}`, assetType: "computer" });
  if (res.status !== 201) throw new Error(`device seed failed: ${JSON.stringify(res.data)}`);
}
const ticketIds = [];
for (let i = 0; i < TICKETS; i++) {
  const client = i % 3 === 0 ? userA : custA;
  const res = await client.post("/api/tickets", { title: `Load ticket ${i}`, description: "Generated by the load test.", category: "other", priority: "normal", impact: "single_user" });
  if (res.status !== 201) throw new Error(`ticket seed failed: ${JSON.stringify(res.data)}`);
  ticketIds.push(res.data.ticket.id);
}

const pick = (list) => list[Math.floor(Math.random() * list.length)];
const scenarios = [
  ["staff dashboard", () => tech.get("/api/dashboard")],
  ["staff ticket list", () => tech.get("/api/tickets?page=1&limit=20&status=active")],
  ["staff ticket search", () => admin.get("/api/tickets?q=Load%20ticket%201&limit=20")],
  ["ticket detail", () => admin.get(`/api/tickets/${pick(ticketIds)}`)],
  ["customer dashboard", () => custA.get("/api/dashboard")],
  ["customer ticket list", () => custA.get("/api/tickets?page=1&limit=20")],
  ["device list", () => admin.get("/api/devices?page=1&limit=20")],
  ["customer reply", () => custA.post(`/api/tickets/${pick(ticketIds)}/notes`, { body: "Any update?", kind: "reply" })],
  ["staff work log", () => tech.post(`/api/tickets/${pick(ticketIds)}/notes`, { body: "Checked remotely.", kind: "work_log", minutesSpent: 5 })],
];

const stats = new Map(scenarios.map(([name]) => [name, { times: [], errors: 0, statuses: {} }]));
const deadline = Date.now() + DURATION_MS;
console.log(`Running ${CONCURRENCY} concurrent workers for ${DURATION_MS / 1000}s against ${TICKETS} tickets and ${DEVICES} devices`);

async function worker() {
  while (Date.now() < deadline) {
    const [name, run] = pick(scenarios);
    const started = performance.now();
    let status = 0;
    try {
      status = (await run()).status;
    } catch {
      status = -1;
    }
    const entry = stats.get(name);
    entry.times.push(performance.now() - started);
    entry.statuses[status] = (entry.statuses[status] || 0) + 1;
    if (status < 200 || status >= 300) entry.errors += 1;
  }
}

const startedAt = performance.now();
await Promise.all(Array.from({ length: CONCURRENCY }, worker));
const elapsed = (performance.now() - startedAt) / 1000;

function percentile(sorted, p) {
  if (!sorted.length) return 0;
  return sorted[Math.min(sorted.length - 1, Math.floor((p / 100) * sorted.length))];
}

let total = 0;
let failed = 0;
const rows = [];
for (const [name, entry] of stats) {
  const sorted = entry.times.sort((a, b) => a - b);
  total += sorted.length;
  failed += entry.errors;
  rows.push({ scenario: name, requests: sorted.length, errors: entry.errors, p50_ms: percentile(sorted, 50).toFixed(1), p95_ms: percentile(sorted, 95).toFixed(1), p99_ms: percentile(sorted, 99).toFixed(1), statuses: JSON.stringify(entry.statuses) });
}
console.table(rows);
console.log(`Total ${total} requests in ${elapsed.toFixed(1)}s = ${(total / elapsed).toFixed(0)} requests/s, ${failed} non-2xx responses`);

child.kill();
await new Promise((resolve) => child.once("exit", resolve));
fs.rmSync(dataDir, { recursive: true, force: true });
process.exit(failed ? 1 : 0);
